#!/usr/bin/env python3
"""Generate a signature table (sigtable_<fw>.h) for the live offsets tool.

Development helper. Given a firmware's kernel text/data dumps and the existing
source/offsets/off_<fw>.c table, this emits a C header that the on-console
payload (pl5-offsets.c) uses to locate every offset by scanning live memory.

For every struct field it picks one of four resolution modes:

  CONST   the field is a compile-time constant (struct field offset / physical
          base) that does not move between firmwares.
  SIG     the bytes at the 13.20 offset are unique within the dump, so the tool
          can verify the expected offset and, failing that, scan for it.
  HINT    we know the expected offset but have no unique signature; the tool
          emits the expected value and marks it unverified.
  MISSING the field is still unknown (0 in off_<fw>.c); emitted as 0.

Usage:
  gen_sigtable.py --fw 1320 \
      --text dumps/kernel_text_1320.bin \
      --data dumps/data_dump_88m.bin \
      --offsets source/offsets/off_1320.c \
      -o tools/sigtable_1320.h
"""
import argparse
import re

# Fields that are pure constants (identical on every firmware).
CONST_FIELDS = {
    "VMSPACE_VM_VMID": 0x1E4,
    "VMSPACE_VM_PMAP": 0x1D8,
    "HV_LOADER_PA_REGULAR": 0x062800000,
    "HV_LOADER_PA_PRO": 0x8E0800000,
}

MAX_SIG = 32


def unique_sig(img, off):
    for ln in range(2, MAX_SIG + 1):
        cand = bytes(img[off:off + ln])
        if len(cand) < ln:
            return b""
        first = img.find(cand)
        if img.find(cand, first + 1) == -1:
            return cand
    return b""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fw", required=True)
    ap.add_argument("--text", required=True)
    ap.add_argument("--data", required=True)
    ap.add_argument("--offsets", required=True)
    ap.add_argument("--struct", required=True,
                    help="include/offsets.h (defines the full field order)")
    ap.add_argument("-o", "--out", required=True)
    args = ap.parse_args()

    text = open(args.text, "rb").read()
    data = open(args.data, "rb").read()
    img = bytearray(text) + bytearray(data)
    text_end = len(text)

    # Full field order comes from the struct; values come from off_<fw>.c
    # (fields absent there are simply 0/unknown).
    struct_src = open(args.struct).read()
    body = struct_src.split("typedef struct _offset_list", 1)[1]
    body = body.split("} offset_list;", 1)[0]
    order = re.findall(r"uint64_t\s+([A-Z0-9_]+)\s*;", body)

    vals = {}
    for name, val in re.findall(r"\.\s*([A-Z0-9_]+)\s*=\s*(0x[0-9A-Fa-f]+)",
                                open(args.offsets).read()):
        vals[name] = int(val, 16)

    lines = []
    for name in order:
        off = vals.get(name, 0)
        if name in CONST_FIELDS:
            mode, region, exp, value, sig = 1, 0, CONST_FIELDS[name], CONST_FIELDS[name], b""
        elif name.startswith("HV_SYM_"):
            mode, region, exp, value, sig = 3, 2, off, off, b""
        elif off == 0:
            mode, region, exp, value, sig = 0, 0, 0, 0, b""
        else:
            region = 0 if off < len(text) else 1
            sig = unique_sig(img, off)
            mode = 2 if sig else 3
            exp = value = off
        sigbytes = ", ".join("0x%02x" % b for b in sig) if sig else "0"
        lines.append('  {"%-40s %d, %d, 0x%07x, 0x%07x, %2d, {%s}},'
                     % (name + '",', mode, region, exp, value, len(sig), sigbytes))

    header = """/* Auto-generated by tools/gen_sigtable.py -- do not edit. */
#ifndef PL5_SIGTABLE_H
#define PL5_SIGTABLE_H
#include <stdint.h>

#define PL5_SIGTABLE_FW 0x%(fw)s
#define PL5_SIG_MAX %(maxsig)d
#define PL5_KERNEL_TEXT_SIZE 0x%(textsize)x
#define PL5_KERNEL_DATA_SIZE 0x%(datasize)x

enum { PL5_MODE_MISSING = 0, PL5_MODE_CONST, PL5_MODE_SIG, PL5_MODE_HINT };
enum { PL5_REGION_KERNEL = 0, PL5_REGION_DATA = 1, PL5_REGION_HV = 2 };

typedef struct {
  const char *name;
  uint8_t     mode;
  uint8_t     region;
  uint64_t    expected;
  uint64_t    value;
  uint8_t     sig_len;
  uint8_t     sig[PL5_SIG_MAX];
} pl5_off_t;

static const pl5_off_t pl5_off_table[] = {
%(table)s
};
#define PL5_OFF_TABLE_LEN (sizeof(pl5_off_table) / sizeof(pl5_off_table[0]))

#endif /* PL5_SIGTABLE_H */
""" % {"fw": args.fw, "maxsig": MAX_SIG,
       "textsize": text_end,
       "datasize": len(data),
       "table": "\n".join(lines)}

    with open(args.out, "w") as f:
        f.write(header)
    print("wrote %s: %d entries" % (args.out, len(lines)))


if __name__ == "__main__":
    main()
